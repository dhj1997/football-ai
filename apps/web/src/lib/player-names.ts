// Normalize accents, punctuation, and case
function normalize(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function containsChinese(value: string): boolean {
  return /[\u3400-\u9fff]/.test(value);
}

