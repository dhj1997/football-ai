export function to_chinese_player_name(name: string): string {
  if (!name) return "待核验球员";
  const trimmed = name.trim();
  if (containsChinese(trimmed)) {
    return trimmed;
  }
  const normalized = normalize(trimmed);
  return PLAYER_NAMES_ZH[normalized] ?? "待核验球员";
}

export function is_reviewed_player_name(name: string): boolean {
  if (!name) return false;
  const trimmed = name.trim();
  return containsChinese(trimmed) || normalize(trimmed) in PLAYER_NAMES_ZH;
}
